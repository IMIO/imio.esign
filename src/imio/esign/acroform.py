# -*- coding: utf-8 -*-
"""Detection and validation of the acroform tags of a signable file.

A signable file may carry one tag per signer, telling the external signing service where to
paste the signature image, like {{#"ID":"Signer1","Size":{"Height":"70","Width":"200"}#}}
and one seal tag, for the seal image, like
{{#"ID":"SCEAU","Size":{"Height":"200","Width":"200"}#}}
"""

from Acquisition import aq_base
from collections import OrderedDict
from imio.esign import _
from imio.esign import logger
from imio.esign.interfaces import IContextUidProvider
from imio.esign.utils import get_session_info
from imio.helpers.content import uuidToObject
from io import BytesIO
from jsonschema import Draft4Validator
from jsonschema import ValidationError
from Products.CMFPlone.utils import safe_unicode
from xml.sax.saxutils import unescape
from zope.annotation.interfaces import IAnnotations
from zope.component import getAdapter
from zope.i18n import translate

import hashlib
import json
import re
import subprocess
import zipfile


try:
    from plone.protect.utils import safeWrite
except ImportError:  # plone.protect < 3

    def safeWrite(obj, request=None):
        pass


# DOTALL: in a raw extracted text, a tag can be wrapped over lines
ACROFORM_TAG_RE = re.compile(r"\{\{#(.*?)#\}\}", re.DOTALL)
POSITIVE_INT_STRING = {"type": "string", "pattern": "^[1-9][0-9]*$"}
# what the signing service expects between {{# and #}}, once wrapped in braces
TAG_VALIDATOR = Draft4Validator(
    {
        "required": ["ID", "Size"],
        "additionalProperties": False,
        "properties": {
            "ID": {"type": "string", "pattern": "^(Signer[1-9][0-9]*|SCEAU)$"},
            "Size": {
                "type": "object",
                "required": ["Height", "Width"],
                "additionalProperties": False,
                "properties": {"Height": POSITIVE_INT_STRING, "Width": POSITIVE_INT_STRING},
            },
        },
    }
)
XML_TAG_RE = re.compile(r"<[^>]*>")
WHITESPACE_RE = re.compile(r"\s+")
PDFTOTEXT = "pdftotext"
# annotation of a file holding its esign data, like its acroform tags
FILE_ANNOTATION_KEY = "imio.esign"

# content type -> path, inside the zipped document, of the xml part holding the text
ZIPPED_XML_PARTS = {
    "application/vnd.oasis.opendocument.text": "content.xml",
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document": "word/document.xml",
}


def _pdf_text(data):
    """Return the text of a pdf, read by the poppler pdftotext binary."""
    process = subprocess.Popen(
        [PDFTOTEXT, "-q", "-enc", "UTF-8", "-", "-"],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    out, err = process.communicate(data)
    if process.returncode != 0:
        raise RuntimeError("pdftotext failed: {}".format(err))
    return safe_unicode(out)


def _zipped_xml_text(data, part_name):
    """Return the text of the given xml part of a zipped document (odt, docx).

    The entities have to be resolved: a document generated by appy/POD stores the double
    quotes of a tag as &quot;, so the tag would never be recognised (PARAF-503).
    """
    zip_file = zipfile.ZipFile(BytesIO(data))
    try:
        xml = safe_unicode(zip_file.read(part_name))
    finally:
        zip_file.close()
    return unescape(XML_TAG_RE.sub(u" ", xml), {u"&quot;": u'"', u"&apos;": u"'"})


def extract_text(nbf):
    """Return the text of a file field, with every whitespace character removed."""
    if nbf is None or not getattr(nbf, "data", None):
        return u""
    try:
        if nbf.contentType == "application/pdf":
            text = _pdf_text(nbf.data)
        elif nbf.contentType in ZIPPED_XML_PARTS:
            text = _zipped_xml_text(nbf.data, ZIPPED_XML_PARTS[nbf.contentType])
        else:
            return u""
    except OSError:
        logger.error("Cannot run '%s': the signature tags of pdf files are not checked!", PDFTOTEXT)
        return u""
    except Exception:
        logger.debug("Could not extract the text of file '%s'", nbf.filename, exc_info=True)
        return u""
    return WHITESPACE_RE.sub(u"", text)


def get_tag_ids(nbf):
    """Return the acroform tag ids of a file field, reading its text only once.

    :return: the signer number of every valid signature tag, in document order, the number
             of valid seal tags, and the malformed tags
    """
    numbers = []
    seals = 0
    malformed = []
    for payload in ACROFORM_TAG_RE.findall(extract_text(nbf)):
        try:
            tag = json.loads(u"{" + payload + u"}")
            TAG_VALIDATOR.validate(tag)
        except (ValueError, ValidationError):
            malformed.append(u"{{#" + payload + u"#}}")
            continue
        if tag["ID"] == u"SCEAU":
            seals += 1
        else:
            numbers.append(int(tag["ID"][len(u"Signer"):]))
    return numbers, seals, malformed


def validate_signer_numbers(numbers, nb_signers):
    """Return the acroform tag error messages for one file.

    A file is valid when it holds no tag at all, or exactly one tag per signer from Signer1
    to Signer<nb_signers>
    """
    if not numbers:
        return []
    counts = {}
    for nb in numbers:
        counts[nb] = counts.get(nb, 0) + 1
    errors = []
    for nb in sorted(counts):
        if counts[nb] > 1:
            errors.append(_("The signature tag of Signer${nb} is present ${count} times.",
                            mapping={"nb": nb, "count": counts[nb]}))
        if nb > nb_signers:
            errors.append(_("There is a signature tag for Signer${nb} but ${count} signer(s) are defined.",
                            mapping={"nb": nb, "count": nb_signers}))
    for nb in range(1, nb_signers + 1):
        if nb not in counts:
            errors.append(_("The signature tag of Signer${nb} is missing.", mapping={"nb": nb}))
    return errors


def validate_seal_count(count, seal):
    """Return the acroform seal tag error messages for one file.

    A file is valid when it holds no seal tag, or exactly one while a seal is defined.
    """
    if not count:
        return []
    if not seal:
        return [_("There is a seal tag but no seal is defined.")]
    if count > 1:
        return [_("The seal tag is present ${count} times.", mapping={"count": count})]
    return []


def check_tags(numbers, seal_count, malformed, nb_signers, seal=False):
    """Return the acroform tag error messages of tags found in a file, see get_tag_ids.

    :param nb_signers: number of signers, or None when the signature tags are unused
    :param seal: whether a seal is defined on the container
    """
    errors = [_("The tag ${tag} is malformed.", mapping={"tag": tag}) for tag in malformed]
    if nb_signers is not None:
        errors += validate_signer_numbers(numbers, nb_signers)
    return errors + validate_seal_count(seal_count, seal)


def check_file(obj, nb_signers, seal=False, stored=False):
    """Return the acroform tag error messages of a content object holding a file.

    :param nb_signers: number of signers, or None when the signature tags are unused
    :param seal: whether a seal is defined on the container
    :param stored: trust the stored acroform tags, see get_file_acroform_tags
    """
    tags = get_file_acroform_tags(obj, stored)
    return check_tags(tags["signers"], tags["seals"], tags["malformed"], nb_signers, seal)


def get_file_fingerprint(nbf):
    """Return the md5 of the data of a file field, None when there is no data."""
    data = nbf is not None and getattr(nbf, "data", None) or None
    if not data:
        return None
    return hashlib.md5(data).hexdigest()


def get_file_acroform_tags(obj, stored=False):
    """Return the acroform tags of the file of p_obj, stored with its md5 in the annotation of p_obj,
    the file is only read again when its md5 changed.

    :param stored: trust the stored tags, without computing the md5
    :return: {"md5": ..., "signers": [...], "seals": ..., "malformed": [...]}
    """
    annotation = IAnnotations(obj).get(FILE_ANNOTATION_KEY, {})
    tags = annotation.get("acroform_tags")
    if tags is not None and stored:
        return tags
    nbf = getattr(obj, "file", None)
    md5 = get_file_fingerprint(nbf)
    if tags is not None and tags["md5"] == md5:
        return tags
    numbers, seal_count, malformed = get_tag_ids(nbf)
    tags = {"md5": md5, "signers": numbers, "seals": seal_count, "malformed": malformed}
    if md5 is None:  # no file
        return tags
    # the dict is replaced, never changed in place, so it is persisted
    IAnnotations(obj)[FILE_ANNOTATION_KEY] = dict(annotation, acroform_tags=tags)
    # a cache, also written when the errors are displayed
    safeWrite(obj)
    safeWrite(aq_base(obj).__annotations__)
    return tags


def get_session_acroform_errors(session_id, stored=False):
    """Return the acroform tag errors of the files of a session, checked against its signers.

    :param session_id: internal session id
    :param stored: trust the acroform tags stored on the files, see get_file_acroform_tags
    :return: OrderedDict {file uid: (file object, context uid, [error messages])}, holding
             only the files in error
    """
    res = OrderedDict()
    session = get_session_info(session_id)
    if not session:
        return res
    nb_signers = len(session.get("signers", []))
    seal = session.get("seal", False)
    for file_info in session["files"]:
        obj = uuidToObject(uuid=file_info["uid"], unrestricted=True)
        if obj is None:
            continue
        errors = check_file(obj, nb_signers, seal, stored)
        if errors:
            context_uid = getAdapter(obj, IContextUidProvider).get_context_uid()
            res[file_info["uid"]] = (obj, context_uid, errors)
    return res


def join_errors(messages):
    """Return the translated error messages of a file on one line, without the final period,
    to be followed by ": " and the file, "error: file", not "error.: file".

    :param messages: translated error messages of the file
    """
    return u" ".join([safe_unicode(msg) for msg in messages]).rstrip(u".")


def format_errors(label, messages, request):
    """Return a one line readable summary of the acroform tag errors of a file,
    the errors followed by the label identifying the file.

    :param label: label identifying the file
    :param messages: error messages of the file
    :param request: used to translate the messages
    """
    errors = join_errors([translate(msg, context=request) for msg in messages])
    return u"{}: {}".format(errors, safe_unicode(label))
